-- Eneles Archives: travaux collaboratifs, versions immuables et modération après publication.

create schema if not exists private;
revoke all on schema private from public, anon, authenticated;

create table if not exists public.travaux (
  id bigint generated by default as identity primary key,
  document_id bigint not null references public."Document"(id) on delete restrict,
  auteur_id uuid not null references auth.users(id) on delete restrict,
  auteur_nom text not null default 'Contributeur',
  titre text not null check (char_length(btrim(titre)) between 3 and 180),
  type text not null default 'autre'
    check (type in ('resume','dissertation','lecon','correction','autre')),
  contenu jsonb not null default '[]'::jsonb
    check (jsonb_typeof(contenu) = 'array'),
  statut text not null default 'publie'
    check (statut in ('publie','masque')),
  moderation_note text,
  masked_at timestamptz,
  masked_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists travaux_document_publie_idx
  on public.travaux(document_id, created_at desc) where statut = 'publie';
create index if not exists travaux_auteur_idx on public.travaux(auteur_id, created_at desc);

create table if not exists public.versions_travaux (
  id bigint generated by default as identity primary key,
  travail_id bigint not null references public.travaux(id) on delete restrict,
  numero integer not null check (numero > 0),
  titre text not null,
  type text not null,
  contenu jsonb not null check (jsonb_typeof(contenu) = 'array'),
  auteur_id uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  unique (travail_id, numero)
);
create index if not exists versions_travaux_historique_idx
  on public.versions_travaux(travail_id, numero desc);

create table if not exists public.signalements_travaux (
  id bigint generated by default as identity primary key,
  travail_id bigint not null references public.travaux(id) on delete restrict,
  signale_par uuid references auth.users(id) on delete set null,
  motif text not null
    check (motif in ('contenu_inapproprie','plagiat','information_erronee','spam','droits_auteur','autre')),
  details text,
  statut text not null default 'nouveau'
    check (statut in ('nouveau','en_cours','traite')),
  created_at timestamptz not null default now()
);
create index if not exists signalements_travaux_statut_idx
  on public.signalements_travaux(statut, created_at desc);
create index if not exists signalements_travaux_travail_idx
  on public.signalements_travaux(travail_id, created_at desc);

-- Le journal est écrit par un déclencheur privé : les clients ne peuvent ni
-- fabriquer, ni modifier, ni supprimer directement des versions historiques.
create or replace function private.eneles_enregistrer_version_travail()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public, auth, private
as $$
declare
  prochain_numero integer;
begin
  if tg_op = 'UPDATE' then
    if new.titre is not distinct from old.titre
       and new.type is not distinct from old.type
       and new.contenu is not distinct from old.contenu then
      return new;
    end if;
  end if;

  select coalesce(max(numero), 0) + 1
    into prochain_numero
    from public.versions_travaux
   where travail_id = new.id;

  insert into public.versions_travaux
    (travail_id, numero, titre, type, contenu, auteur_id)
  values
    (new.id, prochain_numero, new.titre, new.type, new.contenu, coalesce(auth.uid(), new.auteur_id));

  return new;
end;
$$;
revoke all on function private.eneles_enregistrer_version_travail() from public, anon, authenticated;

drop trigger if exists eneles_travaux_version_immutable on public.travaux;
create trigger eneles_travaux_version_immutable
after insert or update on public.travaux
for each row execute function private.eneles_enregistrer_version_travail();

alter table public.travaux enable row level security;
alter table public.versions_travaux enable row level security;
alter table public.signalements_travaux enable row level security;

drop policy if exists travaux_lecture_publique on public.travaux;
create policy travaux_lecture_publique
on public.travaux for select to anon, authenticated
using (
  statut = 'publie'
  or auteur_id = (select auth.uid())
  or public.has_admin_permission('reports')
);

drop policy if exists travaux_creation_propre on public.travaux;
create policy travaux_creation_propre
on public.travaux for insert to authenticated
with check (
  auteur_id = (select auth.uid())
  and statut = 'publie'
  and coalesce((
    select p.banni from public."Profils" p where p.id = (select auth.uid())
  ), false) = false
);

drop policy if exists travaux_modification_auteur on public.travaux;
create policy travaux_modification_auteur
on public.travaux for update to authenticated
using (auteur_id = (select auth.uid()) and statut = 'publie')
with check (auteur_id = (select auth.uid()) and statut = 'publie');

drop policy if exists travaux_moderation_admin on public.travaux;
create policy travaux_moderation_admin
on public.travaux for update to authenticated
using (public.has_admin_permission('reports'))
with check (public.has_admin_permission('reports'));

drop policy if exists versions_travaux_lecture_autorisee on public.versions_travaux;
create policy versions_travaux_lecture_autorisee
on public.versions_travaux for select to anon, authenticated
using (
  exists (
    select 1 from public.travaux t
    where t.id = versions_travaux.travail_id
      and (
        t.statut = 'publie'
        or t.auteur_id = (select auth.uid())
        or public.has_admin_permission('reports')
      )
  )
);

drop policy if exists signalements_travaux_creation_publique on public.signalements_travaux;
create policy signalements_travaux_creation_publique
on public.signalements_travaux for insert to anon, authenticated
with check (
  (signale_par is null or signale_par = (select auth.uid()))
  and exists (
    select 1 from public.travaux t
    where t.id = signalements_travaux.travail_id and t.statut = 'publie'
  )
);

drop policy if exists signalements_travaux_lecture_admin on public.signalements_travaux;
create policy signalements_travaux_lecture_admin
on public.signalements_travaux for select to authenticated
using (public.has_admin_permission('reports'));

drop policy if exists signalements_travaux_traitement_admin on public.signalements_travaux;
create policy signalements_travaux_traitement_admin
on public.signalements_travaux for update to authenticated
using (public.has_admin_permission('reports'))
with check (public.has_admin_permission('reports'));

grant select on public.travaux, public.versions_travaux to anon, authenticated;
grant insert on public.travaux to authenticated;
grant update (titre, type, contenu, updated_at) on public.travaux to authenticated;
grant update (statut, moderation_note, masked_at, masked_by) on public.travaux to authenticated;

grant insert on public.signalements_travaux to anon, authenticated;
grant select on public.signalements_travaux to authenticated;
grant update (statut) on public.signalements_travaux to authenticated;

grant usage, select on sequence public.travaux_id_seq to authenticated;
grant usage, select on sequence public.signalements_travaux_id_seq to anon, authenticated;

-- Images publiques en lecture, mais dépôt limité à un dossier propre à chaque compte.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'travaux-images',
  'travaux-images',
  true,
  5242880,
  array['image/jpeg','image/png','image/webp','image/gif']
)
on conflict (id) do update
set public = excluded.public,
    file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists eneles_travaux_images_upload_own_folder on storage.objects;
create policy eneles_travaux_images_upload_own_folder
on storage.objects for insert to authenticated
with check (
  bucket_id = 'travaux-images'
  and (storage.foldername(name))[1] = (select auth.uid())::text
);